/* ==========================================================================
   IMPLEMENTAÇÃO USBD36: Adicionar Edifício (Building) a uma Facility
   ========================================================================== */

CREATE OR REPLACE PROCEDURE pr_add_building_to_facility(
    p_facility_id IN NUMBER,
    p_name        IN VARCHAR2,
    p_type        IN VARCHAR2
) IS
    v_facility_count NUMBER;
BEGIN
    -- 1. Validação de parâmetros obrigatórios
    IF p_facility_id IS NULL OR p_name IS NULL OR p_type IS NULL THEN
        RAISE_APPLICATION_ERROR(-20003, 'USBD36: Facility ID, Nome e Tipo são obrigatórios.');
END IF;

    -- 2. Verificar se a Facility (Estação) existe
SELECT COUNT(*)
INTO v_facility_count
FROM Facility
WHERE id = p_facility_id;

IF v_facility_count = 0 THEN
        RAISE_APPLICATION_ERROR(-20004, 'USBD36: Estação com ID ' || p_facility_id || ' não encontrada.');
END IF;

    -- 3. Inserção do Edifício
    -- Nota: O ID é gerado automaticamente (GENERATED BY DEFAULT ON NULL AS IDENTITY)
INSERT INTO Building (facility_id, name, type)
VALUES (p_facility_id, p_name, p_type);

-- 4. Feedback e Commit
DBMS_OUTPUT.PUT_LINE('Sucesso: Edifício "' || p_name || '" (' || p_type || ') adicionado à estação ID ' || p_facility_id || '.');
COMMIT;

EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        DBMS_OUTPUT.PUT_LINE('Erro ao adicionar edifício: ' || SQLERRM);
        -- Relançar o erro para que o bloco de teste saiba que falhou
        RAISE;
END;
