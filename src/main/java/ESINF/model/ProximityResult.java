package ESINF.model;

import java.util.List;
import java.util.Objects;

public final class ProximityResult implements Comparable<ProximityResult> {

    private final double distance;
    private final List<Station> stations;

    /**
     * Canonical constructor.
     */
    public ProximityResult(double distance, List<Station> stations) {
        this.distance = distance;
        this.stations = stations;
    }

    // --- Accessor Methods (Getters) ---
    // Note: Record accessors are named without 'get', e.g., 'distance()'

    public double distance() {
        return distance;
    }

    public List<Station> stations() {
        return stations;
    }

    // --- Core Methods for k-NN Logic ---

    /**
     * Compares two results based on distance (natural ordering / Min-Heap).
     * This method is critical for the PriorityQueue used in the k-NN algorithm.
     *
     * @param other The other result to compare to.
     * @return -1 if this distance is smaller, 1 if larger, 0 if equal.
     */
    @Override
    public int compareTo(ProximityResult other) {
        return Double.compare(this.distance, other.distance);
    }

    // --- Standard Methods (Automatically generated by Record) ---

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof ProximityResult that)) return false;
        return Double.compare(distance, that.distance) == 0 &&
                Objects.equals(stations, that.stations);
    }

    @Override
    public int hashCode() {
        return Objects.hash(distance, stations);
    }

    @Override
    public String toString() {
        return "ProximityResult[" +
                "distance=" + distance + ", " +
                "stations=" + stations + ']';
    }
}